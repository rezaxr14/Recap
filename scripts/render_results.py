"""Render a committed benchmark JSON report as Markdown.

The benchmark runner already emits Markdown next to the JSON. This script
produces a stable, linkable results page from the machine-readable record, so
the displayed tables cannot drift from the JSON. It never invents a number:
missing fields are printed as ``null``/``n/a``.

Usage:
    python scripts/render_results.py docs/evidence/.../benchmark_dev_....json \
        --out docs/results.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

BASELINE_ORDER = [
    "no_memory",
    "retry_only",
    "bm25",
    "vector",
    "hybrid_rrf",
    "hybrid_rrf_version_filter",
    "hybrid_rerank",
    "outcome_aware",
    "bm25_chunk",
    "vector_chunk",
    "hybrid_rrf_chunk",
    "outcome_aware_chunk",
    "bm25_naive_chunk",
    "vector_naive_chunk",
    "hybrid_rrf_naive_chunk",
    "outcome_aware_naive_chunk",
]


def _fmt(value: Any, digits: int = 3) -> str:
    if value is None:
        return "null"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def _ci(value: Any) -> str:
    if not isinstance(value, list) or len(value) != 2:
        return "n/a"
    return f"[{_fmt(value[0])}, {_fmt(value[1])}]"


def _ordered_summaries(summary: dict[str, Any]) -> list[tuple[str, dict[str, Any]]]:
    names = list(summary)
    ordered = [name for name in BASELINE_ORDER if name in summary]
    ordered.extend(sorted(name for name in names if name not in ordered))
    return [(name, summary[name]) for name in ordered]


def render(payload: dict[str, Any], *, title: str | None = None) -> str:
    retrieval = payload.get("retrieval") or {}
    protocol = payload.get("protocol") or {}
    agent = payload.get("agent") or {}
    suite = payload.get("suite", "legacy")
    split = payload.get("split", "unknown")
    heading = title or f"RECAP benchmark results: suite `{suite}` / split `{split}`"

    lines: list[str] = [
        f"# {heading}",
        "",
        "> Generated by `scripts/render_results.py` from the committed JSON report. "
        "Do not hand-edit the tables.",
        "",
        "## Provenance",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Generated | `{payload.get('generated_at')}` |",
        f"| Suite / split | `{suite}` / `{split}` |",
        f"| Dataset hash | `{payload.get('dataset_hash')}` |",
        f"| Agent | `{agent.get('kind') or protocol.get('agent')}` "
        f"(`{protocol.get('provider')}`) |",
        f"| Model | `{protocol.get('model') or agent.get('model') or 'n/a'}` |",
        f"| Prompt version | `{protocol.get('prompt_version') or agent.get('prompt_version') or 'n/a'}` |",
        f"| Temperature | `{protocol.get('temperature', agent.get('temperature', 'n/a'))}` |",
        f"| Seed | `{protocol.get('seed', 'n/a')}` |",
        f"| Tool budget | `{protocol.get('max_tool_calls', 'n/a')}` |",
        f"| Embedding model | `{retrieval.get('embedding_model')}` |",
        f"| Embedding dimension | `{retrieval.get('vector_dimension')}` |",
        f"| Embedding fingerprint | `{retrieval.get('embedding_fingerprint')}` |",
        f"| Active memory index | `{retrieval.get('active_index')}` |",
        f"| Reranker | `{retrieval.get('reranker')}` |",
        f"| Workspace | `{payload.get('workspace_id')}` |",
        "",
    ]
    families = protocol.get("failure_families")
    if families:
        lines.extend([f"Failure families: `{', '.join(families)}`.", ""])
    note = protocol.get("note")
    if note:
        lines.extend([f"> {note}", ""])

    summary = payload.get("summary") or {}
    if summary:
        lines.extend(
            [
                "## Summary",
                "",
                "| Baseline | Tasks | Success | 95% CI | recall@3 | MRR | nDCG@3 | "
                "Harmful transfer | Incompatible | Hard-neg selected | Hard-neg outrank | "
                "False abstention |",
                "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
            ]
        )
        for name, stats in _ordered_summaries(summary):
            lines.append(
                "| "
                + " | ".join(
                    [
                        f"`{name}`",
                        _fmt(stats.get("tasks")),
                        _fmt(stats.get("task_success_rate")),
                        _ci(stats.get("task_success_ci95")),
                        _fmt(stats.get("recall_at_3")),
                        _fmt(stats.get("mrr")),
                        _fmt(stats.get("ndcg_at_3")),
                        _fmt(stats.get("harmful_transfer_rate")),
                        _fmt(stats.get("incompatible_selection_rate")),
                        _fmt(stats.get("hard_negative_selection_rate")),
                        _fmt(stats.get("hard_negative_outrank_rate")),
                        _fmt(stats.get("false_abstention_rate")),
                    ]
                )
                + " |"
            )
        lines.append("")

    by_family = payload.get("by_task_family") or {}
    if by_family:
        lines.extend(
            [
                "## By task family",
                "",
                "| Task family | Baseline | Tasks | Success | Harmful transfer | "
                "Incompatible | Hard-neg outrank |",
                "|---|---|---:|---:|---:|---:|---:|",
            ]
        )
        for family in sorted(by_family):
            for name, stats in _ordered_summaries(by_family[family]):
                lines.append(
                    "| "
                    + " | ".join(
                        [
                            f"`{family}`",
                            f"`{name}`",
                            _fmt(stats.get("tasks")),
                            _fmt(stats.get("task_success_rate")),
                            _fmt(stats.get("harmful_transfer_rate")),
                            _fmt(stats.get("incompatible_selection_rate")),
                            _fmt(stats.get("hard_negative_outrank_rate")),
                        ]
                    )
                    + " |"
                )
        lines.append("")

    performance = payload.get("performance") or {}
    if performance:
        lines.extend(["## Performance", "", "| Metric | Value |", "|---|---:|"])
        for key in sorted(performance):
            lines.append(f"| `{key}` | {_fmt(performance[key])} |")
        lines.append("")

    agent_limit = (
        "- The benchmark agent is the deterministic reference agent, not an LLM."
        if agent.get("kind") != "llm"
        else (
            "- The benchmark agent is a real configured LLM in a deterministic mock environment; "
            "provider failures are recorded as failed runs."
        )
    )
    lines.extend(
        [
            "## Limits",
            "",
            agent_limit,
            "- The hashing embedder is lexical, not semantic; a report using it is not a "
            "semantic-retrieval measurement.",
            "- CIs resample tasks within one run; they are not seed-paired intervals.",
            "- Chunk rows can be degenerate when the split has no same-environment distractor set.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path, help="benchmark JSON report")
    parser.add_argument("--out", type=Path, required=True, help="Markdown output path")
    parser.add_argument("--title", default=None)
    args = parser.parse_args()

    payload = json.loads(args.report.read_text(encoding="utf-8"))
    markdown = render(payload, title=args.title)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(markdown, encoding="utf-8")
    print(f"wrote {args.out} ({len(markdown.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
